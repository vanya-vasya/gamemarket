/** Deterministic gradient for a game tile so the whole site stays inside the brand palette. */
export const gamePalette = (slug: string) => {
  let hash = 0;
  for (const char of slug) hash = (hash * 31 + char.charCodeAt(0)) >>> 0;
  return PALETTES[hash % PALETTES.length];
};

